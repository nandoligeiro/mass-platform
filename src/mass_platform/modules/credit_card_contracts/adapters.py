class SyntheticCreditCardContractCatalog:
    def __init__(self, contracts: Sequence[CreditCardContract] | None = None) -> None:
        dataset = tuple(contracts) if contracts is not None else _build_synthetic_dataset()
        self._contracts = dataset
        self._by_id = {item.contract_id: item for item in dataset}

    def list_all(self) -> Sequence[CreditCardContract]:
        return self._contracts

    def get(self, contract_id: str) -> CreditCardContract | None:
        return self._by_id.get(contract_id)
