def _card(
    card_id: str,
    bin_code: str,
    last4: str,
    brand: CardBrand,
    card_type: CardType,
    ownership: CardOwnership,
    status: CardStatus,
    expiry: str,
    *,
    contactless: bool = True,
    international: bool = True,
    wallets: tuple[str, ...] = (),
) -> CreditCard:
    return CreditCard(
        card_id=card_id,
        masked_pan=f"{bin_code[:4]} {bin_code[4:]}•• •••• {last4}",
        bin=bin_code,
        last4=last4,
        brand=brand,
        card_type=card_type,
        ownership=ownership,
        status=status,
        expiry=expiry,
        contactless_enabled=contactless,
        international_enabled=international,
        digital_wallet_tokens=wallets,
    )


